// The legal documents shown in Réglages → À propos are the repository's own
// TERMS.md, PRIVACY.md and LICENSE, embedded at build time: one source of
// truth, no hand-kept copy that could drift from what GitHub publishes.
val legalDocuments = mapOf(
    "TERMS" to "TERMS.md",
    "PRIVACY" to "PRIVACY.md",
    "AGPL" to "LICENSE",
)
val legalRoot: File = rootProject.projectDir
val generateLegalTexts by tasks.registering {
    val sources = legalDocuments.mapValues { (_, path) -> legalRoot.resolve(path) }
    inputs.files(sources.values)
    val output = layout.buildDirectory.dir("generated/legal/kotlin")
    outputs.dir(output)
    doLast {
        val file = output.get().file("com/ravenemu/shared/LegalTexts.kt").asFile
        file.parentFile.mkdirs()
        val code = StringBuilder()
        code.append("package com.ravenemu.shared\n\n")
        code.append("// Generated by :shared:generateLegalTexts from the repository's legal documents.\n")
        code.append("internal object LegalTexts {\n")
        for ((name, source) in sources) {
            code.append("    val ").append(name).append(": String = \"")
            for (char in source.readText()) {
                when (char) {
                    '\\' -> code.append("\\\\")
                    '"' -> code.append("\\\"")
                    '$' -> code.append("\\$")
                    '\n' -> code.append("\\n")
                    '\t' -> code.append("\\t")
                    '\r' -> Unit
                    else -> code.append(char)
                }
            }
            code.append("\"\n")
        }
        code.append("}\n")
        file.writeText(code.toString())
    }
}

kotlin {
    androidLibrary {
        namespace = "com.ravenemu.shared"
        compileSdk = 37
        minSdk = 26
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
        androidResources {
